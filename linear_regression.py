class MSELoss(LossFunction, LossFunctionClosedFormMixin):

    def __init__(self,
                 analytic_solution_func: Callable[[np.ndarray, np.ndarray], np.ndarray] = None):
        if analytic_solution_func is None:
            self.analytic_solution_func = self._plain_analytic_solution
        else:
            self.analytic_solution_func = analytic_solution_func

    def loss(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> float:
        residual = X @ w - y
        return float(np.mean(residual ** 2))

    def gradient(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> np.ndarray:
        residual = X @ w - y
        return 2.0 / X.shape[0] * X.T @ residual

    def analytic_solution(self, X: np.ndarray, y: np.ndarray) -> np.ndarray:
        return self.analytic_solution_func(X, y)

    @classmethod
    def _plain_analytic_solution(cls, X: np.ndarray, y: np.ndarray) -> np.ndarray:
        # w = (X^T X)^(-1) X^T y
        return np.linalg.solve(X.T @ X, X.T @ y)

    @classmethod
    def _svd_analytic_solution(cls, X: np.ndarray, y: np.ndarray) -> np.ndarray:
        X = np.asarray(X, dtype=float)
        y = np.asarray(y, dtype=float).ravel()
        n, d = X.shape
        k = max(1, min(n, d) - 1)

        U, s, Vt = svds(X, k=k, tol=1e-10, solver="propack")

        mask = s > 1e-10
        U = U[:, mask]
        s = s[mask]
        Vt = Vt[mask, :]

        return Vt.T @ ((U.T @ y) / s)


class L2Regularization(LossFunction):

    def __init__(self, core_loss: LossFunction, mu_rate: float = 1.0):
        self.core_loss = core_loss
        self.mu_rate = mu_rate

    def loss(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> float:
        return self.core_loss.loss(X, y, w) + 0.5 * self.mu_rate * float(np.sum(w ** 2))

    def gradient(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> np.ndarray:
        core_part = self.core_loss.gradient(X, y, w)
        penalty_part = self.mu_rate * w
        return core_part + penalty_part


class CustomLinearRegression(LinearRegressionInterface):
    def __init__(
        self,
        optimizer: AbstractOptimizer,
        loss_function: LossFunction = MSELoss(),
    ):
        self.optimizer = optimizer
        self.optimizer.set_model(self)
        self.loss_function = loss_function
        self.loss_history = []
        self.w = None
        self.X_train = None
        self.y_train = None

    def predict(self, X: np.ndarray) -> np.ndarray:
        return X @ self.w

    def compute_gradients(self,
                          X_batch: np.ndarray | None = None,
                          y_batch: np.ndarray | None = None) -> np.ndarray:
        X = self.X_train if X_batch is None else X_batch
        y = self.y_train if y_batch is None else y_batch
        return self.loss_function.gradient(X, y, self.w)

    def compute_loss(self,
                     X_batch: np.ndarray | None = None,
                     y_batch: np.ndarray | None = None) -> float:
        X = self.X_train if X_batch is None else X_batch
        y = self.y_train if y_batch is None else y_batch
        return self.loss_function.loss(X, y, self.w)

    def fit(self, X: np.ndarray, y: np.ndarray) -> None:
        self.X_train = X.tocsr().astype(float) if sparse.issparse(X) else np.asarray(X, dtype=float)
        self.y_train = np.asarray(y, dtype=float).ravel()
        self.w = np.zeros(self.X_train.shape[1])
        self.loss_history = []
        self.optimizer.optimize()

class LogCoshLoss(LossFunction):

    def loss(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> float:
        z = X @ w - y
        return float(np.mean(np.logaddexp(z, -z) - np.log(2.0)))

    def gradient(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> np.ndarray:
        z = X @ w - y
        return X.T @ np.tanh(z) / X.shape[0]


class HuberLoss(LossFunction):

    def __init__(self, delta: float = 1.0):
        self.delta = delta

    def loss(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> float:
        r = X @ w - y
        a = np.abs(r)
        quad = 0.5 * r ** 2
        lin = self.delta * a - 0.5 * self.delta ** 2
        return float(np.mean(np.where(a <= self.delta, quad, lin)))

    def gradient(self, X: np.ndarray, y: np.ndarray, w: np.ndarray) -> np.ndarray:
        r = X @ w - y
        a = np.abs(r)
        g = np.where(a <= self.delta, r, self.delta * np.sign(r))
        return X.T @ g / X.shape[0]