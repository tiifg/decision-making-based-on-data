import numpy as np
from abc import ABC, abstractmethod
from interfaces import LearningRateSchedule, AbstractOptimizer, LinearRegressionInterface


# ===== Learning Rate Schedules =====
class ConstantLR(LearningRateSchedule):
    def __init__(self, lr: float):
        self.lr = lr

    def get_lr(self, iteration: int) -> float:
        return self.lr


class TimeDecayLR(LearningRateSchedule):
    def __init__(self, lambda_: float = 1.0):
        self.s0 = 1
        self.p = 0.5
        self.lambda_ = lambda_

    def get_lr(self, iteration: int) -> float:
        return self.lambda_ * (self.s0 / (self.s0 + iteration)) ** self.p


# ===== Base Optimizer =====
class BaseDescent(AbstractOptimizer, ABC):
    def __init__(self,
                 lr_schedule: LearningRateSchedule = TimeDecayLR(),
                 tolerance: float = 1e-6,
                 max_iter: int = 1000):
        self.lr_schedule = lr_schedule
        self.tolerance = tolerance
        self.max_iter = max_iter

        self.iteration = 0
        self.model: LinearRegressionInterface = None

    @abstractmethod
    def _update_weights(self) -> np.ndarray:
        pass

    def _step(self) -> np.ndarray:
        delta = self._update_weights()
        self.iteration += 1
        return delta

    def optimize(self) -> None:
        self.iteration = 0
        self.model.loss_history = [self.model.compute_loss()]
        for _ in range(self.max_iter):
            delta = self._step()
            self.model.loss_history.append(self.model.compute_loss())

            if np.any(np.isnan(delta)) or np.any(np.isnan(self.model.w)):
                break
            if np.linalg.norm(delta) ** 2 < self.tolerance:
                break


# ===== Specific Optimizers =====
class VanillaGradientDescent(BaseDescent):
    def _update_weights(self) -> np.ndarray:
        lr = self.lr_schedule.get_lr(self.iteration)
        grad = self.model.compute_gradients()
        delta = -lr * grad
        self.model.w = self.model.w + delta
        return delta


class StochasticGradientDescent(BaseDescent):
    def __init__(self, *args, batch_size=32, **kwargs):
        super().__init__(*args, **kwargs)
        self.batch_size = batch_size

    def _update_weights(self) -> np.ndarray:
        X, y = self.model.X_train, self.model.y_train
        n = X.shape[0]
        idx = np.random.randint(0, n, size=self.batch_size)

        lr = self.lr_schedule.get_lr(self.iteration)
        grad = self.model.compute_gradients(X[idx], y[idx])
        delta = -lr * grad
        self.model.w = self.model.w + delta
        return delta


class SAGDescent(BaseDescent):
    def __init__(self, *args, batch_size=32, **kwargs):
        super().__init__(*args, **kwargs)
        self.grad_memory = None
        self.grad_sum = None
        self.batch_size = batch_size
    def _update_weights(self) -> np.ndarray:
        X, y = self.model.X_train, self.model.y_train
        num_objects, num_features = X.shape

        if self.grad_memory is None:
            self.grad_memory = np.zeros((num_objects, num_features))
            self.grad_sum = np.zeros(num_features)

        idx = np.random.choice(
            num_objects, size=min(self.batch_size, num_objects), replace=False
        )
        for j in idx:
            new_g = self.model.compute_gradients(X[j:j + 1], y[j:j + 1])
            self.grad_sum += new_g - self.grad_memory[j]
            self.grad_memory[j] = new_g

        avg_grad = self.grad_sum / num_objects
        lr = self.lr_schedule.get_lr(self.iteration)
        delta = -lr * avg_grad
        self.model.w = self.model.w + delta
        return delta


class MomentumDescent(BaseDescent):
    def __init__(self, *args, beta=0.9, **kwargs):
        super().__init__(*args, **kwargs)
        self.beta = beta
        self.velocity = None

    def _update_weights(self) -> np.ndarray:
        if self.velocity is None:
            self.velocity = np.zeros_like(self.model.w)

        lr = self.lr_schedule.get_lr(self.iteration)
        grad = self.model.compute_gradients()

        self.velocity = self.beta * self.velocity + lr * grad
        delta = -self.velocity
        self.model.w = self.model.w + delta
        return delta


class Adam(BaseDescent):
    def __init__(self, *args, beta1=0.9, beta2=0.999, eps=1e-8, **kwargs):
        super().__init__(*args, **kwargs)
        self.beta1 = beta1
        self.beta2 = beta2
        self.eps = eps
        self.m = None
        self.v = None

    def _update_weights(self) -> np.ndarray:
        if self.m is None:
            self.m = np.zeros_like(self.model.w)
            self.v = np.zeros_like(self.model.w)

        lr = self.lr_schedule.get_lr(self.iteration)
        grad = self.model.compute_gradients()

        self.m = self.beta1 * self.m + (1 - self.beta1) * grad
        self.v = self.beta2 * self.v + (1 - self.beta2) * grad ** 2

        t = self.iteration + 1
        m_hat = self.m / (1 - self.beta1 ** t)
        v_hat = self.v / (1 - self.beta2 ** t)

        delta = -lr * m_hat / (np.sqrt(v_hat) + self.eps)
        self.model.w = self.model.w + delta
        return delta


